class MeasureOnFixture(unittest.TestCase):
    """measure compares the base commit with the working tree after a repair."""

    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.home = os.path.join(cls.tmp.name, "home")
        cls.repo = fixture_repo.build(os.path.join(cls.tmp.name, "app"), cls.home)
        cls.home = os.path.realpath(cls.home)
        # A doc in Latin-1, so the base side reads non-UTF-8 bytes through git.
        with open(os.path.join(cls.repo, "docs/latin1.md"), "wb") as f:
            f.write("# Caf\xe9\n".encode("latin-1"))
        subprocess.run(["git", "-C", cls.repo, "add", "docs/latin1.md"], check=True)
        subprocess.run(["git", "-C", cls.repo, "-c", "user.name=t", "-c", "user.email=t@t", "-c",
                        "commit.gpgsign=false", "commit", "-q", "-m", "latin1"], check=True)
        base = subprocess.run(["git", "-C", cls.repo, "rev-parse", "HEAD"], capture_output=True,
                              text=True, check=True).stdout.strip()
        # A doc the repair creates and has not committed yet.
        os.makedirs(os.path.join(cls.repo, ".claude/rules"), exist_ok=True)
        with open(os.path.join(cls.repo, ".claude/rules/new-rule.md"), "w") as f:
            f.write("Keep it short.\n")
        # The repair: drop the repeated rule from the runbook, the dead path from the architecture
        # doc, and the orphan note.
        runbook = os.path.join(cls.repo, "docs/runbook.md")
        with open(runbook, encoding="utf-8") as f:
            text = f.read().replace(fixture_repo.RULE, "Back up first; see the restore drill.")
        with open(runbook, "w", encoding="utf-8") as f:
            f.write(text)
        arch = os.path.join(cls.repo, "docs/ARCHITECTURE.md")
        with open(arch, encoding="utf-8") as f:
            text = f.read().replace("The importer lives in `src/legacy/importer.py`.\n", "")
        with open(arch, "w", encoding="utf-8") as f:
            f.write(text)
        os.remove(os.path.join(cls.repo, "docs/notes/old-ideas.md"))
        cls.out = json.loads(run_inventory(cls.repo, cls.home, "measure", "--base", base))
        cls.base_sha = base

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def test_both_sides_are_labelled(self):
        self.assertEqual((self.out["base"]["ref"], self.out["worktree"]["ref"]), (self.base_sha, "worktree"))

    def test_the_working_tree_side_includes_a_new_uncommitted_doc(self):
        self.assertEqual(self.out["worktree"]["words"][".claude/rules/new-rule.md"], 3)
        self.assertNotIn(".claude/rules/new-rule.md", self.out["base"]["words"])
        self.assertEqual(self.out["base"]["words"]["docs/latin1.md"], 2)

    def test_words_per_file_and_in_always_loaded_files(self):
        base, now = self.out["base"], self.out["worktree"]
        self.assertNotIn("docs/notes/old-ideas.md", now["words"])
        cut = len(fixture_repo.RULE.split()) - len("Back up first; see the restore drill.".split())
        self.assertEqual(base["words"]["docs/runbook.md"] - now["words"]["docs/runbook.md"], cut)
        # The runbook is imported by CLAUDE.md, so it counts as always loaded.
        # The new unscoped rule (3 words) loads at session start too.
        self.assertEqual(base["always_loaded_words"] - now["always_loaded_words"], cut - 3)

    def test_repeats_stale_references_and_orphans_go_down(self):
        base, now = self.out["base"], self.out["worktree"]
        self.assertEqual((base["unresolved_refs"], now["unresolved_refs"]), (1, 0))
        self.assertEqual(base["orphans"], ["PROMPTS.md", "docs/latin1.md", "docs/notes/old-ideas.md"])
        self.assertEqual(now["orphans"], ["PROMPTS.md", "docs/latin1.md", "notes-draft.md"])  # untracked
        self.assertEqual(base["duplicated_passages"] - now["duplicated_passages"], 0)
        self.assertGreater(base["duplicated_words"], now["duplicated_words"])


