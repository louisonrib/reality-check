"""Tests of skills/fix-my-context/scripts/inventory.py, through its command line, on the fixture repo."""
import json
import os
import subprocess
import sys
import tempfile
import unittest

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fixture_repo  # noqa: E402

INVENTORY = os.path.join(HERE, "..", "..", "skills", "fix-my-context", "scripts", "inventory.py")


def git_status(repo):
    return subprocess.run(["git", "-C", repo, "status", "--porcelain", "--ignored"],
                          capture_output=True, text=True, check=True).stdout


def run_inventory(repo, home, *args):
    env = dict(os.environ, HOME=home)
    out = subprocess.run([sys.executable, "-I", INVENTORY, *args, repo], env=env,
                         capture_output=True, text=True, check=True)
    return out.stdout


class InventoryOnFixture(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory()
        cls.repo = fixture_repo.build(os.path.join(cls.tmp.name, "app"), os.path.join(cls.tmp.name, "home"))
        cls.home = os.path.realpath(os.path.join(cls.tmp.name, "home"))
        cls.status_before = git_status(cls.repo)
        cls.raw = run_inventory(cls.repo, cls.home)
        cls.out = json.loads(cls.raw)
        cls.files = {(f["scope"], f["path"]): f for f in cls.out["files"]}

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def repo_file(self, path):
        return self.files[("repo", path)]

    def test_lists_tracked_doc_files_with_their_size(self):
        repo_paths = sorted(p for s, p in self.files if s == "repo")
        self.assertEqual(repo_paths, [
            ".claude/rules/docs-writing.md", "AGENTS.md", "CLAUDE.md", "CONTRIBUTING.md", "GLOSSARY.md",
            "PROMPTS.md", "README.md", "TERMS.md", "docs/ARCHITECTURE.md", "docs/notes/old-ideas.md",
            "docs/runbook.md"])
        self.assertEqual(self.repo_file("CONTRIBUTING.md")["lines"], 3)
        self.assertEqual(self.repo_file("CONTRIBUTING.md")["words"], 8)  # whitespace-separated, as wc -w

    def test_creating_commit_names_the_tool_that_created_the_file(self):
        created = self.repo_file("PROMPTS.md")["history"]["created"]
        self.assertEqual(created["subject"], "docforge init: generate PROMPTS.md")
        self.assertIn("Generated by docforge 0.4", created["body"])
        self.assertTrue(created["date"].startswith("2026-07-05T10:00:00"))  # git prints Z or +00:00
        self.assertEqual(created["author"], "Fixture Author")

    def test_growing_doc_shows_its_commits_and_churn(self):
        history = self.repo_file("docs/ARCHITECTURE.md")["history"]
        # 5 lines at creation, then three appended sections of 5 lines each.
        self.assertEqual((history["commits"], history["lines_added"], history["lines_deleted"]), (4, 20, 0))
        self.assertEqual(history["last"]["subject"], "Update architecture doc after the auth feature")

    def test_pointer_graph_holds_links_backticks_imports_and_rule_paths(self):
        edges = {(p["from"], p["to"], p["kind"]) for p in self.out["pointers"]}
        self.assertLessEqual({
            ("README.md", "docs/ARCHITECTURE.md", "link"),
            ("README.md", "CONTRIBUTING.md", "link"),
            ("CLAUDE.md", "docs/runbook.md", "import"),
            ("CLAUDE.md", "docs/ARCHITECTURE.md", "backtick"),
            (".claude/rules/docs-writing.md", "docs/runbook.md", "rule_paths"),
            (".claude/rules/docs-writing.md", "docs/notes/old-ideas.md", "rule_paths"),
        }, edges)
